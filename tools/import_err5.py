#!/usr/bin/env python3
"""Import the National Set of ERR-5 Application Error Codes into data/err5-codes.yml.

    python tools/import_err5.py              # path from inputs.json (err5_xlsx)
    python tools/import_err5.py --xlsx PATH

The national set is maintained by AIRA as a spreadsheet (sheets: Description, Code Ranges, Codes, Reference).
The ACK TAB (June 2026) points to it for ERR-5 values and their implementation priorities. The spreadsheet is
kept local; only the imported codes are committed. Re-runs are deterministic.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from guidecards import REPO, write_yaml  # noqa: E402

OUT = REPO / "data" / "err5-codes.yml"
PRIORITY = {"high": "High", "medium": "Medium", "low": "Low", "n/a": "N/A"}
EXCEL_EPOCH = dt.date(1899, 12, 30)


def clean(v) -> str:
    if v is None:
        return ""
    if isinstance(v, float) and v.is_integer():
        v = int(v)
    return re.sub(r"\s+", " ", str(v)).strip()


def published(v) -> str:
    """Excel date serials become YYYY-MM-DD; other text ("Proposed") is kept."""
    if isinstance(v, dt.datetime):
        return v.date().isoformat()
    s = clean(v)
    if s.isdigit() and 30000 < int(s) < 80000:
        return (EXCEL_EPOCH + dt.timedelta(days=int(s))).isoformat()
    return s


def rows(ws):
    for r in ws.iter_rows(values_only=True):
        if any(c is not None and str(c).strip() for c in r):
            yield r


def read(path: Path) -> dict:
    import openpyxl
    wb = openpyxl.load_workbook(path, data_only=True)

    ranges = []
    for r in rows(wb["Code Ranges"]):
        first = clean(r[0])
        if re.match(r"^\d+\s*[–-]\s*\d+$", first):
            ranges.append({"range": re.sub(r"\s*[–-]\s*", "–", first), "description": clean(r[1]),
                           "example": clean(r[2]) if len(r) > 2 else ""})

    codes, header = [], None
    for r in rows(wb["Codes"]):
        cells = [clean(c) for c in r]
        if header is None:
            if cells and cells[0] == "Class" and "Code" in cells:
                header = {name: i for i, name in enumerate(cells) if name}
            continue
        code = cells[header["Code"]]
        if not code.isdigit():
            continue
        get = lambda name: cells[header[name]] if name in header and header[name] < len(cells) else ""  # noqa: E731
        prio = re.split(r"[/(]", get("Implementation Priority"))[0].strip().lower()
        item = {
            "code": code,
            "class": get("Class"),
            "concept": get("Concept"),
            "description": get("Description"),
            "priority": PRIORITY.get(prio, get("Implementation Priority")),
            "status": get("Status"),
        }
        for key, col in (("notes", "Notes"), ("sources", "Source(s)")):
            if get(col):
                item[key] = get(col)
        see = [s.strip() for s in re.split(r"[;,]", get("See Also")) if s.strip()]
        if see:
            item["see_also"] = see
        pub = published(r[header["Published"]]) if "Published" in header and header["Published"] < len(r) else ""
        if pub:
            item["published"] = pub
        codes.append(item)

    seen = set()
    for c in codes:
        if c["code"] in seen:
            raise SystemExit(f"Duplicate ERR-5 code {c['code']}")
        seen.add(c["code"])
    return {"ranges": ranges, "codes": codes}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--xlsx", type=Path, help="National ERR-5 code set (default: err5_xlsx in inputs.json)")
    args = ap.parse_args()
    path = args.xlsx
    if path is None:
        inputs = REPO / "inputs.json"
        cfg = json.loads(inputs.read_text(encoding="utf-8")) if inputs.exists() else {}
        if not cfg.get("err5_xlsx"):
            ap.error("No --xlsx given and no err5_xlsx in inputs.json (see inputs.example.json).")
        path = Path(cfg["err5_xlsx"])
    data = read(path)
    m = re.search(r"(\d{4}-\d{2}-\d{2})", path.name)
    out = {
        "title": "National Set of ERR-5 Application Error Codes for Immunization ACK Messaging",
        "maintainer": "AIRA",
        "version": m.group(1) if m else "",
        "status": "Not yet published. AIRA is preparing this version for posting on the AIRA repository.",
        "contact": "info@immregistries.org",
        **data,
    }
    write_yaml(OUT, out, header=(
        "Generated by tools/import_err5.py from AIRA's National Set of ERR-5 Application Error Codes (xlsx, kept local).\n"
        "Do not edit; re-run the import when AIRA updates the set."))
    n = {p: sum(1 for c in data["codes"] if c["priority"] == p) for p in ("High", "Medium", "Low", "N/A")}
    print(f"Imported {len(data['codes'])} codes in {len(data['ranges'])} ranges "
          f"({n['High']} High, {n['Medium']} Medium, {n['Low']} Low, {n['N/A']} N/A): {OUT}")


if __name__ == "__main__":
    main()
