def assign_card_ids(roots: list[Node], ledger: dict) -> dict:
    entries = ledger.get("cards", [])
    for e in entries:
        e.setdefault("retired", False)
    used = {e["id"] for e in entries}
    matched: set[str] = set()
    nodes = [n for r in roots for n in r.walk()]

    # Path traces with occurrence counts for repeated sibling titles.
    for node in nodes:
        parent_path = node.parent.path if node.parent else ""
        siblings = node.parent.children if node.parent else roots
        same = [s for s in siblings if norm_title(s.title) == norm_title(node.title)]
        suffix = f" #{same.index(node) + 1}" if len(same) > 1 else ""
        node.path = (parent_path + " / " if parent_path else "") + node.title + suffix

    def key_path(path: str) -> str:
        return " / ".join(norm_title(p) for p in path.split(" / "))

    by_bookmark = {e["bookmark"]: e for e in entries if e.get("bookmark")}
    by_path = {key_path(e["path"]): e for e in entries}

    def take(node: Node, entry: dict):
        node.id = entry["id"]
        matched.add(entry["id"])
        entry.update(title=node.title, path=node.path, parent=node.parent.id if node.parent else None, retired=False)
        if node.bookmark:
            entry["bookmark"] = node.bookmark
        else:
            entry.pop("bookmark", None)

    for node in nodes:  # document order: parents are resolved before children
        entry = by_bookmark.get(node.bookmark) if node.bookmark else None
        if entry is None or entry["id"] in matched:
            entry = by_path.get(key_path(node.path))
        if entry is not None and entry["id"] not in matched:
            take(node, entry)
            continue
        parent_id = node.parent.id if node.parent else None
        candidates = [e for e in entries if e["id"] not in matched and e.get("parent") == parent_id
                      and not (e.get("bookmark") and node.bookmark and e["bookmark"] != node.bookmark)]
        best, best_score = None, 0.0
        for e in candidates:
            score = difflib.SequenceMatcher(None, norm_title(e["title"]), norm_title(node.title)).ratio()
            if score > best_score:
                best, best_score = e, score
        if best is not None and best_score >= 0.75:
            take(node, best)
            continue
        # A card moved to another parent keeps its ID when its title is unchanged and unique.
        moved = [e for e in entries if e["id"] not in matched and not e.get("retired")
                 and norm_title(e["title"]) == norm_title(node.title)]
        if len(moved) == 1 and sum(norm_title(n.title) == norm_title(node.title) for n in nodes) == 1:
            take(node, moved[0])
            continue
        new_id = slugify(node.title)
        if new_id in used:
            parent_slug = parent_id or "guide"
            room = MAX_ID_LEN - len(new_id) - 1
            new_id = f"{parent_slug[:max(room, 10)].rstrip('-')}-{new_id}"[:MAX_ID_LEN].rstrip("-")
        base, n = new_id, 2
        while new_id in used:
            new_id = f"{base[:MAX_ID_LEN - 3]}-{n}"
            n += 1
        used.add(new_id)
        entry = {"id": new_id}
        entries.append(entry)
        take(node, entry)

    order = {n.id: i for i, n in enumerate(nodes)}
    for e in entries:
        if e["id"] not in matched:
            e["retired"] = True
    active = sorted((e for e in entries if not e["retired"]), key=lambda e: order[e["id"]])
    retired = sorted((e for e in entries if e["retired"]), key=lambda e: e["id"])
    clean = []
    for e in active + retired:
        item = {"id": e["id"], "title": e["title"], "parent": e.get("parent")}
        if e.get("bookmark"):
            item["bookmark"] = e["bookmark"]
        item["path"] = e["path"]
        if e["retired"]:
            item["retired"] = True
        clean.append(item)
    return {"cards": clean}


def assign_statement_ids(card_id: str, statements: list[dict], ledger: dict) -> None:
    book = ledger.setdefault(card_id, {"next": 1, "statements": []})
    known = book["statements"]
    taken: set[str] = set()

    def norm(t):
        return " ".join(t.lower().split())

    assigned: dict[int, dict] = {}
    # 1. Unchanged text keeps its ID.
    for i, st in enumerate(statements):
        k = next((k for k in known if k["id"] not in taken and norm(k["text"]) == norm(st["text"])), None)
        if k is not None:
            assigned[i] = k
            taken.add(k["id"])
    # 2. Reworded text: best-scoring pairs first, across the whole card.
    pairs = []
    for i, st in enumerate(statements):
        if i in assigned:
            continue
        for k in known:
            if k["id"] not in taken:
                score = difflib.SequenceMatcher(None, norm(k["text"]), norm(st["text"])).ratio()
                if score >= 0.6:
                    pairs.append((score, i, k["id"], k))
    for score, i, kid, k in sorted(pairs, key=lambda p: (-p[0], p[1], p[2])):
        if i not in assigned and kid not in taken:
            assigned[i] = k
            taken.add(kid)
    # 3. New text takes the next unused number.
    for i, st in enumerate(statements):
        k = assigned.get(i)
        if k is None:
            k = {"id": f"{card_id}--s{book['next']}", "text": st["text"]}
            book["next"] += 1
            known.append(k)
            taken.add(k["id"])
        k["text"] = st["text"]
        k.pop("retired", None)
        st["id"] = k["id"]
    for k in known:
        if k["id"] not in taken:
            k["retired"] = True


