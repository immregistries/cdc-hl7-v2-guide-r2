FOLDER_SLUG_LEN = 32  # keeps paths well under the Windows 260-character limit


def folder_name(position: int, card_id: str) -> str:
    """Folder names are for people browsing the repository; identity is in card.yml."""
    slug = card_id if len(card_id) <= FOLDER_SLUG_LEN else card_id[:FOLDER_SLUG_LEN].rsplit("-", 1)[0]
    return f"{position:02d}-{slug}"


def table_markdown(rows: list[list[str]]) -> str:
    if not rows:
        return ""
    width = max(len(r) for r in rows)
    rows = [r + [""] * (width - len(r)) for r in rows]
    lines = ["| " + " | ".join(rows[0]) + " |", "|" + "---|" * width]
    lines += ["| " + " | ".join(r) + " |" for r in rows[1:]]
    return "\n".join(lines) + "\n"


def write_card(node: Node, folder: Path, content: CardContent) -> None:
    meta: dict = {"id": node.id, "title": node.title}
    if content.figures:
        meta["figures"] = []
        for f in content.figures:
            (folder / f["file"]).parent.mkdir(parents=True, exist_ok=True)
            (folder / f["file"]).write_bytes(f["_data"])
            meta["figures"].append({k: v for k, v in f.items() if not k.startswith("_")})
    if content.tables:
        meta["tables"] = []
        for t in content.tables:
            write_text(folder / t["file"], table_markdown(t["_rows"]))
            meta["tables"].append({k: v for k, v in t.items() if not k.startswith("_")})
    if content.references:
        meta["references"] = sorted(content.references)
    if node.glossary:
        meta["glossary"] = node.glossary
    write_yaml(folder / "card.yml", meta)
    if content.narrative:
        write_text(folder / "narrative.md", "\n\n".join(content.narrative).strip() + "\n")
    if content.statements:
        write_yaml(folder / "statements.yml", [
            {k: s[k] for k in ("id", "verb", "verbs", "actor", "text") if k in s} for s in content.statements
        ])


def write_index(roots: list[Node], stats: dict, path: Path) -> None:
    lines = [
        "# Card index",
        "",
        "<!-- Generated by tools/convert_narrative.py. Do not edit. -->",
        "",
        f"{stats['cards']} cards · {stats['statements']} conformance statements · "
        f"{stats['figures']} figures · {stats['tables']} tables",
        "",
        "Columns after each title: card ID, then narrative blocks (¶), statements (S), figures (F).",
        "",
    ]

    def emit(nodes, prefix, depth, base):
        for i, n in enumerate(nodes, 1):
            num = f"{prefix}{i}"
            rel = f"{base}/{folder_name(i, n.id)}"
            c = stats["content"][n.id]
            counts = f"¶{len(c.narrative)} S{len(c.statements)}" + (f" F{len(c.figures)}" if c.figures else "")
            lines.append(f"{'  ' * depth}- {num} [{n.title}]({rel}/) `{n.id}` {counts}")
            emit(n.children, num + ".", depth + 1, rel)

    emit(roots, "", 0, ".")
    write_text(path, "\n".join(lines) + "\n")


