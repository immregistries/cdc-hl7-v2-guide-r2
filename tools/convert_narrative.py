def split_sections(blocks: list[Block], overrides: dict):
    """Split the document by Heading 1 into front matter, narrative, and appendices."""
    stop = norm_title(overrides.get("stop_at", ""))
    appendix_rules = {norm_title(k): v for k, v in (overrides.get("appendices") or {}).items()}
    front, narrative, appendices = [], [], defaultdict(list)
    mode, current_appendix = "front", None
    unknown = []
    for b in blocks:
        if b.kind == "heading" and b.level == 1:
            key = norm_title(b.text)
            if not key:
                continue
            if mode in ("front", "narrative") and key != stop and key not in appendix_rules:
                mode = "narrative"
            elif key == stop:
                mode = "structured"
            elif key in appendix_rules:
                mode, current_appendix = "appendix", appendix_rules[key]
                continue
            else:
                mode, current_appendix = "appendix", "skip"
                unknown.append(b.text)
                continue
        if mode == "front":
            front.append(b)
        elif mode == "narrative":
            narrative.append(b)
        elif mode == "appendix":
            appendices[current_appendix].append(b)
    return front, narrative, appendices, unknown


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--docx", type=Path, help="Narrative draft (default: narrative_docx in inputs.json)")
    parser.add_argument("--cards", type=Path, default=CARDS_DIR, help="Card tree to (re)generate")
    parser.add_argument("--data", type=Path, default=DATA_DIR, help="Data folder for glossary and references")
    parser.add_argument("--report", type=Path, default=REPO / "output" / "conversion-report.md")
    args = parser.parse_args(argv)

    docx_path = args.docx
    if docx_path is None:
        inputs = REPO / "inputs.json"
        if not inputs.exists():
            parser.error("No --docx given and no inputs.json (copy inputs.example.json).")
        docx_path = Path(json.loads(inputs.read_text(encoding="utf-8"))["narrative_docx"])
    if not docx_path.exists():
        parser.error(f"Draft not found: {docx_path}")

    cards_dir: Path = args.cards
    meta_dir = cards_dir / META
    overrides = read_yaml(meta_dir / "overrides.yml", {}) or {}
    reader = DocReader(docx_path)
    blocks = reader.blocks()
    front, narrative, appendices, unknown = split_sections(blocks, overrides)

    notes_global: list[str] = []
    if unknown:
        notes_global.append("Unrecognized top-level sections were skipped: " + "; ".join(unknown))
    roots = build_tree(narrative, overrides, notes_global)

    ledger = assign_card_ids(roots, read_yaml(meta_dir / "ids.yml", {}) or {})
    statement_ledger = read_yaml(meta_dir / "statement-ids.yml", {}) or {}

    nodes = [n for r in roots for n in r.walk()]
    contents: dict[str, CardContent] = {}
    for node in nodes:
        content = render_content(node, overrides)
        assign_statement_ids(node.id, content.statements, statement_ledger)
        contents[node.id] = content
    for card_id, book in statement_ledger.items():
        if card_id not in contents:
            for k in book["statements"]:
                k["retired"] = True

    # ---- write the card tree (regenerated in full)
    for entry in cards_dir.iterdir() if cards_dir.exists() else []:
        if entry.is_dir() and not entry.name.startswith(("_", ".")):
            shutil.rmtree(entry)

    def emit(nodes_, parent_folder: Path):
        for i, n in enumerate(nodes_, 1):
            folder = parent_folder / folder_name(i, n.id)
            folder.mkdir(parents=True, exist_ok=True)
            write_card(n, folder, contents[n.id])
            emit(n.children, folder)

    emit(roots, cards_dir)

    stats = {
        "cards": len(nodes),
        "statements": sum(len(c.statements) for c in contents.values()),
        "figures": sum(len(c.figures) for c in contents.values()),
        "tables": sum(len(c.tables) for c in contents.values()),
        "content": contents,
    }
    write_index(roots, stats, cards_dir / "INDEX.md")
    write_yaml(meta_dir / "ids.yml", ledger, header="Card ID ledger. " + GENERATED_HEADER)
    write_yaml(meta_dir / "statement-ids.yml",
               {k: statement_ledger[k] for k in [n.id for n in nodes] + sorted(set(statement_ledger) - {n.id for n in nodes})},
               header="Statement ID ledger. " + GENERATED_HEADER)

    for n in nodes:
        promoted = [s["id"] for s in contents[n.id].statements if s.get("_promoted")]
        if promoted:
            contents[n.id].notes.append("promoted-statements: " + ", ".join(promoted))
    card_notes = {n.id: n.notes + contents[n.id].notes for n in nodes if n.notes or contents[n.id].notes}
    write_yaml(meta_dir / "conversion-notes.yml",
               {"document": notes_global + [f"Word comments in the draft (not published): {reader.comment_count}"],
                "cards": card_notes},
               header="What the converter noticed. Read by the quality checks. " + GENERATED_HEADER)

    digest = hashlib.sha256(docx_path.read_bytes()).hexdigest()
    front_text = [b.text for b in front if b.kind == "para"]
    write_yaml(meta_dir / "source.yml", {
        "converter_version": CONVERTER_VERSION,
        "narrative_docx": {"file": docx_path.name, "sha256": digest, "front_matter": front_text},
    }, header=GENERATED_HEADER)

    # ---- data files from the glossary sections and appendices
    data_header = "Generated by tools/convert_narrative.py from the narrative draft. Do not edit before cutover."
    for node in nodes:
        g = contents[node.id].glossary
        if g:
            write_yaml(args.data / f"{node.glossary}.yml", {"card": node.id, **g}, header=data_header)
    if appendices.get("glossary"):
        write_yaml(args.data / "glossary.yml", parse_glossary(appendices["glossary"]), header=data_header)
    if appendices.get("references"):
        write_yaml(args.data / "references.yml", parse_references(appendices["references"]), header=data_header)
    if appendices.get("change-history"):
        write_yaml(args.data / "change-history.yml", parse_change_history(appendices["change-history"]), header=data_header)

    # ---- report (local only)
    retired = [e for e in ledger["cards"] if e.get("retired")]
    lines = [
        "# Conversion report", "",
        f"- Draft: `{docx_path.name}` (sha256 `{digest[:12]}…`)",
        f"- Cards: {stats['cards']} · statements: {stats['statements']} · figures: {stats['figures']} · tables: {stats['tables']}",
        f"- Retired card IDs (no longer in the draft): {len(retired)}",
        f"- Word comments not carried over: {reader.comment_count}",
        "", "## Document notes", "",
    ] + [f"- {n}" for n in notes_global] + ["", "## Card notes", ""]
    for cid, notes in card_notes.items():
        lines += [f"- `{cid}`"] + [f"  - {n}" for n in notes]
    write_text(args.report, "\n".join(lines) + "\n")

    print(f"Converted {docx_path.name}: {stats['cards']} cards, {stats['statements']} statements, "
          f"{stats['figures']} figures, {stats['tables']} tables; {len(retired)} retired IDs.")
    print(f"Report: {args.report}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
