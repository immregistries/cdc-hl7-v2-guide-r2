@dataclass
class Block:
    kind: str                      # heading | para | list | image | table
    text: str = ""                 # plain, cleaned
    md: str = ""                   # inline Markdown
    level: int = 0                 # heading level, or list indent level
    ordered: bool = False
    style: str = ""
    emphasized: bool = False       # every visible run bold or underlined
    bold_prefix: str = ""          # leading bold text (glossary entries)
    rest_md: str = ""              # Markdown after the bold prefix
    bookmark: str | None = None    # IGAMT section GUID bookmark, if any
    image: tuple | None = None     # (bytes, extension)
    rows: list = field(default_factory=list)
    internal_links: int = 0
    urls: list = field(default_factory=list)

    @property
    def caption(self):
        return CAPTION_RE.match(self.text) if self.kind == "para" else None


def _escape_md(text: str) -> str:
    return text.replace("\\", "\\\\").replace("*", "\\*").replace("<", "\\<")


def _run_flags(run_el, paragraph) -> tuple[bool, bool, bool]:
    run = Run(run_el, paragraph)
    bold, italic, underline = run.bold, run.italic, run.underline
    style = run.style if run_el.rPr is not None and run_el.rPr.rStyle is not None else None
    if style is not None:
        bold = bold if bold is not None else style.font.bold
        italic = italic if italic is not None else style.font.italic
    return bool(bold), bool(italic), bool(underline)


def _run_text(run_el) -> str:
    out = []
    for child in run_el:
        tag = child.tag
        if tag == W + "t":
            out.append(child.text or "")
        elif tag in (W + "tab", W + "br", W + "cr"):
            out.append(" ")
        elif tag == W + "noBreakHyphen":
            out.append("-")
    return "".join(out)


class DocReader:
    def __init__(self, path: Path):
        self.document = docx.Document(str(path))
        self.part = self.document.part
        self.numfmt = self._numbering_formats()
        self.comment_count = len(self.document.element.body.findall(".//" + W + "commentRangeStart"))

    def _numbering_formats(self) -> dict:
        formats = {}
        try:
            numbering = self.part.numbering_part.element
        except (KeyError, NotImplementedError, AttributeError):
            return formats
        abstract = {}
        for an in numbering.findall(W + "abstractNum"):
            levels = {}
            for lvl in an.findall(W + "lvl"):
                fmt = lvl.find(W + "numFmt")
                levels[lvl.get(W + "ilvl")] = fmt.get(W + "val") if fmt is not None else "bullet"
            abstract[an.get(W + "abstractNumId")] = levels
        for num in numbering.findall(W + "num"):
            ref = num.find(W + "abstractNumId")
            if ref is not None:
                formats[num.get(W + "numId")] = abstract.get(ref.get(W + "val"), {})
        return formats

    # ------------------------------------------------------------------ inline

    def _segments(self, paragraph: Paragraph):
        """Yield (text, bold, italic, underline, href) in document order."""
        stats = {"internal": 0, "urls": []}

        def visit(el, href):
            for child in el:
                tag = child.tag
                if tag == W + "r":
                    text = _run_text(child)
                    if text:
                        b, i, u = _run_flags(child, paragraph)
                        yield text, b, i, u, href
                elif tag == W + "hyperlink":
                    rid = child.get(R + "id")
                    link = None
                    if rid and rid in self.part.rels and self.part.rels[rid].is_external:
                        link = self.part.rels[rid].target_ref
                        stats["urls"].append(link)
                    elif child.get(W + "anchor"):
                        stats["internal"] += 1
                    yield from visit(child, link)
                elif tag in (W + "pPr", W + "rPr"):
                    continue
                elif tag in (W + "del", W + "moveFrom"):
                    continue
                else:
                    yield from visit(child, href)

        segments = list(visit(paragraph._p, None))
        return segments, stats

    @staticmethod
    def _render(segments) -> str:
        merged = []
        for text, b, i, _u, href in segments:
            if merged and merged[-1][1:] == (b, i, href):
                merged[-1] = (merged[-1][0] + text, b, i, href)
            else:
                merged.append((text, b, i, href))
        out = []
        for text, b, i, href in merged:
            text = text.replace(" ", " ").replace("\t", " ")
            if not text.strip():
                out.append(text)
                continue
            lead = text[: len(text) - len(text.lstrip())]
            trail = text[len(text.rstrip()):]
            core = _escape_md(text.strip())
            if href:
                core = f"[{core}]({href})"
            if b and i:
                core = f"***{core}***"
            elif b:
                core = f"**{core}**"
            elif i:
                core = f"*{core}*"
            out.append(lead + core + trail)
        md = re.sub(r"[ \r\n]+", " ", "".join(out)).strip()
        if re.match(r"^(#|>|[-+] |\d+[.)] )", md):
            md = "\\" + md
        return md

    # ------------------------------------------------------------------ blocks

    def blocks(self) -> list[Block]:
        out: list[Block] = []
        for el in self.document.element.body.iterchildren():
            if el.tag == W + "tbl":
                out.append(self._table(Table(el, self.document)))
            elif el.tag == W + "p":
                out.extend(self._paragraph(Paragraph(el, self.document)))
        return out

    def _table(self, table: Table) -> Block:
        rows = []
        for row in table.rows:
            cells = []
            for cell in row.cells:
                parts = [self._render(self._segments(p)[0]) for p in cell.paragraphs]
                cells.append("<br>".join(x for x in parts if x).replace("|", "\\|"))
            rows.append(cells)
        return Block(kind="table", rows=rows)

    def _paragraph(self, p: Paragraph) -> list[Block]:
        out = []
        el = p._p
        for blip in el.iter(A + "blip"):
            rid = blip.get(R + "embed")
            if rid and rid in self.part.related_parts:
                image_part = self.part.related_parts[rid]
                ext = Path(str(image_part.partname)).suffix.lower() or ".png"
                out.append(Block(kind="image", image=(image_part.blob, ext)))
        style = p.style.name if p.style is not None else ""
        segments, stats = self._segments(p)
        text = clean_text("".join(s[0] for s in segments))
        if not text:
            return out
        md = self._render(segments)
        visible = [s for s in segments if s[0].strip()]
        emphasized = bool(visible) and all(s[1] or s[3] for s in visible)
        bold_prefix_segments = []
        for s in segments:
            if s[0].strip() and not s[1]:
                break
            bold_prefix_segments.append(s)
        bold_prefix = clean_text("".join(s[0] for s in bold_prefix_segments))
        rest_md = self._render(segments[len(bold_prefix_segments):]) if bold_prefix else ""
        bookmark = next(
            (b.get(W + "name") for b in el.iter(W + "bookmarkStart") if GUID_RE.match(b.get(W + "name") or "")),
            None,
        )
        block = Block(
            kind="para", text=text, md=md, style=style, emphasized=emphasized,
            bold_prefix=bold_prefix, rest_md=rest_md, bookmark=bookmark,
            internal_links=stats["internal"], urls=stats["urls"],
        )
        heading = re.match(r"^Heading (\d)$", style)
        num = el.find(f"{W}pPr/{W}numPr")
        typed_bullet = re.match(r"^[•·▪◦‣]\s*", block.text)
        if typed_bullet and not heading:
            # A bullet character typed into an ordinary paragraph.
            block.kind = "list"
            block.text = block.text[typed_bullet.end():]
            block.md = re.sub(r"^\s*(\*\*|\*)?[•·▪◦‣]\s*", r"\1", block.md)
            return out + [block]
        if heading:
            block.kind, block.level = "heading", int(heading.group(1))
        elif num is not None or style.startswith("List"):
            block.kind = "list"
            if num is not None:
                ilvl = num.find(W + "ilvl")
                num_id = num.find(W + "numId")
                block.level = int(ilvl.get(W + "val")) if ilvl is not None else 0
                fmt = self.numfmt.get(num_id.get(W + "val") if num_id is not None else "", {}).get(str(block.level), "bullet")
                block.ordered = fmt not in ("bullet", "none")
            else:
                block.ordered = "Number" in style
        out.append(block)
        return out


# =========================================================================== tree


@dataclass
class Node:
    title: str
    kind: str                       # heading | topic
    level: int
    bookmark: str | None = None
    parent: "Node | None" = None
    blocks: list = field(default_factory=list)
    children: list = field(default_factory=list)
    notes: list = field(default_factory=list)
    mode: str = "split"             # split | no_split | glossary
    glossary: str | None = None
    path: str = ""
    id: str = ""

    def walk(self):
        yield self
        for child in self.children:
            yield from child.walk()


def is_subhead(block: Block) -> bool:
    if block.kind != "para" or not block.emphasized or block.caption:
        return False
    if len(block.text) > 120 or block.text.endswith((".", ";", ",")):
        return False
    return not find_verbs(block.text)


def build_tree(blocks: list[Block], overrides: dict, notes_global: list) -> list[Node]:
    context = {norm_title(t) for t in overrides.get("context_titles", [])}
    no_split = {norm_title(t) for t in overrides.get("no_split", [])}
    glossary = {norm_title(k): v for k, v in (overrides.get("glossary_sections") or {}).items()}
    nest = {norm_title(k): {norm_title(c) for c in v} for k, v in (overrides.get("nest") or {}).items()}
    nest_used: set[str] = set()

    roots: list[Node] = []
    stack: list[Node] = []
    current: Node | None = None
    nest_parent: Node | None = None       # sub-heading currently collecting nested sub-headings
    for block in blocks:
        if block.kind == "heading":
            nest_parent = None
            node = Node(title=block.text, kind="heading", level=block.level, bookmark=block.bookmark)
            key = norm_title(block.text)
            if key in no_split:
                node.mode = "no_split"
            elif key in glossary:
                node.mode, node.glossary = "glossary", glossary[key]
            while stack and stack[-1].level >= block.level:
                stack.pop()
            if stack:
                node.parent = stack[-1]
                stack[-1].children.append(node)
            else:
                roots.append(node)
            stack.append(node)
            current = node
            continue
        if current is None:
            notes_global.append(f"Content before the first heading was ignored: {block.text[:80]!r}")
            continue
        heading = stack[-1]
        if is_subhead(block):
            key = norm_title(block.text)
            if key in context:
                current = heading
                if heading.blocks or heading.children:
                    heading.notes.append(f"'{block.text}' appears after other content; its text was added to this card's narrative.")
                heading.notes.append(f"context-heading: {block.text}")
                continue
            if heading.mode == "no_split":
                current.blocks.append(Block(kind="para", text=block.text, md=f"**{_escape_md(block.text)}**"))
                continue
            if heading.mode == "glossary":
                heading.blocks.append(Block(kind="gloss-head", text=block.text))
                continue
            parent = heading
            if nest_parent is not None and key in nest[norm_title(nest_parent.title)]:
                parent = nest_parent
            else:
                nest_parent = None
            topic = Node(title=block.text, kind="topic", level=parent.level + 1,
                         bookmark=block.bookmark, parent=parent)
            parent.children.append(topic)
            if parent is heading and key in nest:
                nest_parent = topic
                nest_used.add(key)
            current = topic
            continue
        current.blocks.append(block)
    for key in set(nest) - nest_used:
        notes_global.append(f"overrides.yml nest rule matched nothing: {key!r}")
    return roots


