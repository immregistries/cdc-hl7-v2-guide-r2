def is_statement_paragraph(text: str) -> bool:
    """A one-sentence paragraph that reads as a requirement: it contains a
    conformance verb and opens with its actor or with a condition."""
    if not find_verbs(text):
        return False
    probe = re.sub(r"\b(e\.g|i\.e|etc|vs|U\.S|approx)\.", "X", text)
    if len(re.findall(r"[.!?](?:\s|$)", probe)) > 1:
        return False
    return bool(subject_of(text)) or bool(re.match(r"^(If|When|Where|For|Unless|Once|After|Before|In)\b", text))


def caption_number(raw: str):
    """Caption numbers are ints ("21"), or strings when suffixed ("10a")."""
    return int(raw) if raw.isdigit() else raw.lower()


@dataclass
class CardContent:
    narrative: list = field(default_factory=list)     # Markdown blocks
    statements: list = field(default_factory=list)
    figures: list = field(default_factory=list)
    tables: list = field(default_factory=list)
    references: set = field(default_factory=set)
    notes: list = field(default_factory=list)
    glossary: dict | None = None


def render_content(node: Node, overrides: dict) -> CardContent:
    content = CardContent()
    alt = {str(k): v for k, v in (overrides.get("figure_alt") or {}).items()}
    promote = overrides.get("promote_prose_statements", True) and node.id not in set(overrides.get("no_promote", []))
    pending_list: list[str] = []
    seen_statement = False
    noted_interleave = False
    blocks = node.blocks

    def flush_list():
        if pending_list:
            content.narrative.append("\n".join(pending_list))
            pending_list.clear()

    def narrative_after_statement():
        nonlocal noted_interleave
        if seen_statement and not noted_interleave:
            content.notes.append("Narrative text follows conformance statements in the draft; on the card, statements are shown after the narrative.")
            noted_interleave = True

    if node.mode == "glossary":
        content.glossary = parse_key_terms(node)
        blocks = content.glossary.pop("_intro_blocks")

    i = 0
    while i < len(blocks):
        b = blocks[i]
        if b.internal_links:
            content.notes.append(f"Internal Word cross-reference(s) rendered as plain text: {b.text[:60]!r}")
        if b.kind == "image":
            flush_list()
            number, caption = None, ""
            j = i + 1
            if j < len(blocks) and blocks[j].caption:
                m = blocks[j].caption
                number, caption = caption_number(m.group(2)), clean_text(m.group(3))
                i = j
            fid = f"fig-{number}" if number is not None else f"fig-{node.id}-{len(content.figures) + 1}"
            data, ext = b.image
            if number is None:
                content.notes.append("Figure without a 'Figure n:' caption.")
            content.figures.append({
                "id": fid, "file": f"{fid}{ext}", "number": number, "caption": caption,
                "alt": alt.get(str(number), ""), "_data": data,
            })
        elif b.kind == "table":
            flush_list()
            n = len(content.tables) + 1
            table = {"id": f"table-{n}", "file": f"table-{n}.md", "caption": "", "_rows": b.rows}
            if i + 1 < len(blocks) and blocks[i + 1].caption:
                m = blocks[i + 1].caption
                table["number"] = caption_number(m.group(2))
                table["caption"] = clean_text(m.group(3))
                i += 1
            content.tables.append(table)
        elif b.kind == "list":
            verbs = find_verbs(b.text)
            if verbs:
                flush_list()
                st = {"verb": verbs[0], "actor": actor_of(b.text), "text": b.text}
                if len(set(verbs)) > 1:
                    st["verbs"] = list(dict.fromkeys(verbs))
                content.statements.append(st)
                seen_statement = True
            else:
                narrative_after_statement()
                marker = "1." if b.ordered else "-"
                pending_list.append("  " * b.level + f"{marker} {b.md}")
        elif b.kind == "para":
            flush_list()
            if b.caption:
                content.notes.append(f"Caption without an image: {b.text[:60]!r}")
                content.narrative.append(b.md)
            elif promote and is_statement_paragraph(b.text):
                verbs = find_verbs(b.text)
                st = {"verb": verbs[0], "actor": actor_of(b.text), "text": b.text, "_promoted": True}
                if len(set(verbs)) > 1:
                    st["verbs"] = list(dict.fromkeys(verbs))
                content.statements.append(st)
                seen_statement = True
            else:
                narrative_after_statement()
                content.narrative.append(b.md)
        i += 1
    flush_list()
    for text in content.narrative + [s["text"] for s in content.statements]:
        content.references.update(int(x) for x in CITATION_RE.findall(text))
    return content


def parse_key_terms(node: Node) -> dict:
    """Key Terms: bold lines followed by another bold line are groups; others are terms."""
    blocks = [b for b in node.blocks if b.kind in ("gloss-head", "para", "list")]
    intro = []
    k = 0
    while k < len(blocks) and blocks[k].kind != "gloss-head":
        intro.append(blocks[k])
        k += 1
    groups, current_group, current_term = [], None, None
    rest = blocks[k:]
    for idx, b in enumerate(rest):
        if b.kind == "gloss-head":
            nxt = rest[idx + 1] if idx + 1 < len(rest) else None
            if nxt is None or nxt.kind == "gloss-head":
                current_group = {"name": b.text, "terms": []}
                groups.append(current_group)
                current_term = None
            else:
                if current_group is None:
                    current_group = {"name": "", "terms": []}
                    groups.append(current_group)
                current_term = {"term": b.text, "definition": ""}
                current_group["terms"].append(current_term)
        elif current_term is not None:
            line = b.md if b.kind == "para" else "- " + b.md
            sep = "\n\n" if b.kind == "para" else "\n"
            current_term["definition"] = (current_term["definition"] + sep + line).strip()
    return {"_intro_blocks": intro, "title": node.title, "groups": groups}


