def parse_glossary(blocks: list[Block]) -> dict:
    groups, intro, current = [], [], None
    for b in blocks:
        if b.kind not in ("para", "list"):
            continue
        if b.emphasized and len(b.text) < 60 and not b.rest_md:
            current = {"name": b.text, "entries": []}
            groups.append(current)
        elif b.bold_prefix and b.rest_md:
            definition = re.sub(r"^\s*\\?[-–—:]\s*", "", b.rest_md)
            if current is None:
                current = {"name": "", "entries": []}
                groups.append(current)
            current["entries"].append({"term": b.bold_prefix.rstrip(" -–—:"), "definition": definition})
        elif current is None:
            intro.append(b.md)
        elif current["entries"]:
            current["entries"][-1]["definition"] += "\n\n" + b.md
    return {"intro": "\n\n".join(intro), "groups": groups}


def parse_references(blocks: list[Block]) -> dict:
    """Entries start at bold lines. A bold line directly followed by another bold
    line is a group header. References are numbered in document order."""
    blocks = [b for b in blocks if b.kind in ("para", "list")]

    def is_url(b):
        return bool(b.urls) or b.text.startswith(("http://", "https://"))

    intro, items, group = [], [], ""
    for idx, b in enumerate(blocks):
        if b.emphasized and not is_url(b):
            nxt = blocks[idx + 1] if idx + 1 < len(blocks) else None
            if nxt is not None and nxt.emphasized and not is_url(nxt):
                group = b.text
                continue
            item = {"number": len(items) + 1, "title": b.text, "description": "", "url": ""}
            if group:
                item["group"] = group
            items.append(item)
        elif not items:
            intro.append(b.md)
        elif is_url(b) and not items[-1]["url"]:
            items[-1]["url"] = b.urls[0] if b.urls else b.text
        else:
            items[-1]["description"] = (items[-1]["description"] + " " + b.text).strip()
    # An entry with no URL that is followed by other entries is a group header.
    groups, refs, group = [], [], ""
    for k, item in enumerate(items):
        if not item["url"] and k + 1 < len(items):
            group = item["title"]
            groups.append({"name": group, "description": item["description"]})
            continue
        if group and "group" not in item:
            item["group"] = group
        item["number"] = len(refs) + 1
        refs.append(item)
    result = {"intro": "\n\n".join(intro)}
    if groups:
        result["groups"] = groups
    result["references"] = refs
    return result


def parse_change_history(blocks: list[Block]) -> dict:
    tables = [b for b in blocks if b.kind == "table"]
    rows = []
    for t in tables:
        if not t.rows:
            continue
        header = [clean_text(re.sub(r"[*\\]", "", h)) or f"column_{i + 1}" for i, h in enumerate(t.rows[0])]
        for r in t.rows[1:]:
            if any(c.strip() for c in r):
                rows.append({header[i] if i < len(header) else f"column_{i + 1}": c for i, c in enumerate(r)})
    return {"changes": rows}


