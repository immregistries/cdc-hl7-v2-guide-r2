#!/usr/bin/env python3
"""Publish the TA questions into quality/ta/, with the names of who asked kept out.

    python tools/import_ta.py              # source folder from inputs.json (ta_dir) or TA_REVIEW_DIR
    python tools/import_ta.py --dir PATH

The TA Questions pages (tools/ta_review.py, author view only) compare what implementers have asked AIRA's technical
assistance service with the guide. The questions are consolidated outside this repository from AIRA's TA records, which
name the jurisdictions, IIS vendors, and people who asked. This import publishes the consolidated questions only:

- kept: each question and its consolidated answer, its segment/field and topic, how often and in which years it was
  asked, its status, and the IG clarifications suggested when the records were consolidated;
- left out: the individual records (each time it was asked, as asked), their TA notes and source references, and the
  exact dates;
- names: the replacements in <ta_dir>/scrub.yml are applied, and the import fails if a name it forbids, or a US state
  or territory name, is still there. scrub.yml lists the names, so it stays outside the repository.

This is a privacy curtain, not de-identification: nothing here is sensitive, but the guide has no reason to say who
asked. EHR products are kept by name; they do not ask AIRA directly.

The assessments (quality/ta/assess/<page>.yml: does the guide answer each question?) are written by hand in this
repository. A page's assessment is copied from <ta_dir>/assess/ only when the repository does not have one yet.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from guidecards import REPO, read_yaml, write_yaml  # noqa: E402

OUT = REPO / "quality" / "ta"
HEADER = "Generated by tools/import_ta.py from the TA consolidation, with the names of who asked left out. Do not edit."
KEEP = ("id", "group", "fields", "question", "answer", "flags", "status", "asked", "messages", "related")
STATE_NAMES = [
    "Alabama", "Alaska", "Arizona", "Arkansas", "California", "Colorado", "Connecticut", "Delaware", "Florida", "Georgia",
    "Hawaii", "Idaho", "Illinois", "Indiana", "Iowa", "Kansas", "Kentucky", "Louisiana", "Maine", "Maryland",
    "Massachusetts", "Michigan", "Minnesota", "Mississippi", "Missouri", "Montana", "Nebraska", "Nevada", "New Hampshire",
    "New Jersey", "New Mexico", "New York", "North Carolina", "North Dakota", "Ohio", "Oklahoma", "Oregon", "Pennsylvania",
    "Rhode Island", "South Carolina", "South Dakota", "Tennessee", "Texas", "Utah", "Vermont", "Virginia", "Washington",
    "West Virginia", "Wisconsin", "Wyoming", "Guam", "Puerto Rico", "American Samoa", "Virgin Islands",
    "District of Columbia", "Philadelphia", "Chicago", "Houston", "San Antonio", "New York City",
]


def source_dir(arg: str | None) -> Path:
    path = arg or os.environ.get("TA_REVIEW_DIR")
    if not path and (REPO / "inputs.json").exists():
        path = json.loads((REPO / "inputs.json").read_text(encoding="utf-8")).get("ta_dir")
    if not path or not (Path(path) / "index.yml").exists():
        raise SystemExit("No TA source folder: pass --dir, set TA_REVIEW_DIR, or add ta_dir to inputs.json")
    return Path(path)


class Scrubber:
    def __init__(self, rules: dict):
        self.replace = [(r["find"], r["with"]) for r in rules.get("replace") or []]
        self.allow = list(rules.get("allow") or [])
        names = list(rules.get("forbid") or []) + STATE_NAMES
        self.forbid = re.compile(r"\b(" + "|".join(re.escape(n) for n in sorted(set(names), key=len, reverse=True)) + r")\b")
        self.used: set[str] = set()
        self.problems: list[str] = []

    def text(self, where: str, value):
        if isinstance(value, list):
            return [self.text(where, v) for v in value]
        if isinstance(value, dict):
            return {k: self.text(f"{where}.{k}", v) for k, v in value.items()}
        if not isinstance(value, str):
            return value
        for find, new in self.replace:
            if find in value:
                value = value.replace(find, new)
                self.used.add(find)
        check = value
        for phrase in self.allow:
            check = check.replace(phrase, "")
        for m in self.forbid.finditer(check):
            self.problems.append(f"{where}: {m.group(0)!r} in ...{check[max(0, m.start() - 40):m.end() + 40]}...")
        return value


def years(dates: list) -> list[int]:
    return sorted({int(str(d)[:4]) for d in dates or [] if str(d)[:4].isdigit()})


def run(src: Path) -> dict:
    scrub = Scrubber(read_yaml(src / "scrub.yml", {}) or {})
    index = read_yaml(src / "index.yml", {}) or {}
    pages_out, total = [], 0
    for entry in index.get("pages", []):
        pid = entry["id"]
        page = read_yaml(src / "pages" / f"{pid}.yml", {}) or {}
        questions = []
        for q in page.get("questions", []):
            out = {k: q[k] for k in KEEP if q.get(k) not in (None, [], "")}
            out["years"] = years(q.get("dates"))
            questions.append(scrub.text(f"pages/{pid}/{q['id']}", out))
        data = {"id": pid, "kind": page.get("kind", entry.get("kind")), "title": page.get("title", entry.get("title"))}
        for k in ("overview", "suggested"):
            if page.get(k):
                data[k] = scrub.text(f"pages/{pid}/{k}", page[k])
        data["questions"] = questions
        pages_out.append(data)
        total += len(questions)
        assess_src, assess_out = src / "assess" / f"{pid}.yml", OUT / "assess" / f"{pid}.yml"
        if assess_src.exists() and not assess_out.exists():
            scrub.text(f"assess/{pid}", assess_src.read_text(encoding="utf-8"))
            assess_out.parent.mkdir(parents=True, exist_ok=True)
            assess_out.write_text(assess_src.read_text(encoding="utf-8"), encoding="utf-8", newline="\n")
    for path in sorted((OUT / "assess").glob("*.yml")) if (OUT / "assess").exists() else []:
        scrub.text(f"quality/ta/assess/{path.stem}", path.read_text(encoding="utf-8"))
    unused = [f for f, _ in scrub.replace if f not in scrub.used]
    if unused:
        print("Note: scrub.yml replacements that matched nothing (already fixed at the source?):", *unused, sep="\n  ")
    if scrub.problems:
        raise SystemExit("Names still present; add a replacement (or an allowed phrase) to scrub.yml:\n  "
                         + "\n  ".join(scrub.problems))
    ex = index.get("excluded") or {}
    write_yaml(OUT / "index.yml", {
        "excluded": {"smm": len(ex.get("smm") or []), "not_generalizable": ex.get("not_generalizable", 0)},
        "pages": [{"id": p["id"], "kind": p["kind"], "title": p["title"], "questions": len(p["questions"])} for p in pages_out],
    }, header=HEADER)
    for p in pages_out:
        write_yaml(OUT / "pages" / f"{p['id']}.yml", p, header=HEADER)
    return {"pages": len(pages_out), "questions": total}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--dir", help="the TA consolidation folder (index.yml, pages/, assess/, scrub.yml)")
    args = parser.parse_args(argv)
    result = run(source_dir(args.dir))
    print(f"Published {result['questions']} TA questions on {result['pages']} pages to {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
